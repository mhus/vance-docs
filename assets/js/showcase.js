/* Shared behaviour of the showcase pages (landing, apps, agents, connect, trust):
   theme toggle and the language menu. English is the markup; translations
   live in assets/i18n/<lang>/ (see the language menu below). */
(function () {
  var root = document.documentElement;

  /* ---- theme toggle — persists choice; default look is light ---- */
  var tStored = null;
  try { tStored = localStorage.getItem("vance-theme"); } catch (e) {}
  if (tStored === "dark" || tStored === "light") root.setAttribute("data-theme", tStored);
  var themeToggle = document.getElementById("theme-toggle");
  var themeIcon = document.getElementById("theme-icon");
  var SUN = '<circle cx="12" cy="12" r="4.2"/><path d="M12 2v2M12 20v2M4.2 4.2l1.4 1.4M18.4 18.4l1.4 1.4M2 12h2M20 12h2M4.2 19.8l1.4-1.4M18.4 5.6l1.4-1.4"/>';
  var MOON = '<path d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8z"/>';
  function isDark() { return (root.getAttribute("data-theme") || "light") === "dark"; }
  function paintTheme() { if (themeIcon) themeIcon.innerHTML = isDark() ? SUN : MOON; }
  paintTheme();
  if (themeToggle) themeToggle.addEventListener("click", function () {
    root.setAttribute("data-theme", isDark() ? "light" : "dark");
    try { localStorage.setItem("vance-theme", isDark() ? "dark" : "light"); } catch (e) {}
    paintTheme();
  });

  /* ---- language menu — English is the markup; other languages are loaded
     from assets/i18n/<lang>/{common,<page>}.json when picked. Those files are
     generated by scripts/translate-site.py in the workbench; a key missing
     there stays English. Default: stored choice, else the browser language. */
  var LANGS = [["en", "English"], ["de", "Deutsch"], ["fr", "Français"], ["es", "Español"], ["ja", "日本語"]];
  var CODES = LANGS.map(function (l) { return l[0]; });
  var me = document.currentScript;
  var base = (me && me.src ? me.src : "/assets/js/showcase.js").replace(/js\/showcase\.js.*$/, "i18n/");
  var page = document.body.getAttribute("data-i18n-page") || "index";
  var nodes = document.querySelectorAll("[data-i18n]");
  nodes.forEach(function (el) { el.dataset.en = el.innerHTML; });
  var cache = {};

  function fetchJson(url) {
    return fetch(url).then(function (r) { return r.ok ? r.json() : {}; }).catch(function () { return {}; });
  }
  function load(lang) {
    if (!cache[lang]) {
      cache[lang] = Promise.all([fetchJson(base + lang + "/common.json"), fetchJson(base + lang + "/" + page + ".json")])
        .then(function (parts) {
          var dict = {}, k;
          for (k in parts[0]) dict[k] = parts[0][k];
          for (k in parts[1]) dict[k] = parts[1][k];
          return dict;
        });
    }
    return cache[lang];
  }

  var label = document.getElementById("lang-label");
  var menu = document.getElementById("lang-menu");
  var langBtn = document.getElementById("lang-toggle");

  function paint(lang, dict) {
    nodes.forEach(function (el) {
      var t = dict && dict[el.getAttribute("data-i18n")];
      el.innerHTML = t != null ? t : el.dataset.en;
    });
    root.setAttribute("lang", lang);
    if (label) label.textContent = lang.toUpperCase();
    if (menu) menu.querySelectorAll("[data-lang]").forEach(function (b) {
      b.setAttribute("aria-checked", b.getAttribute("data-lang") === lang ? "true" : "false");
    });
  }
  function applyLang(lang) {
    if (lang === "en") { paint("en", null); return Promise.resolve(); }
    return load(lang).then(function (dict) { paint(lang, dict); });
  }

  if (menu) {
    LANGS.forEach(function (l) {
      var b = document.createElement("button");
      b.type = "button";
      b.setAttribute("role", "menuitemradio");
      b.setAttribute("data-lang", l[0]);
      b.setAttribute("lang", l[0]);
      b.innerHTML = '<span class="code">' + l[0].toUpperCase() + "</span>" + l[1];
      b.addEventListener("click", function () {
        try { localStorage.setItem("vance-lang", l[0]); } catch (e) {}
        closeMenu();
        applyLang(l[0]);
      });
      menu.appendChild(b);
    });
  }
  function openMenu() { if (menu) { menu.hidden = false; langBtn.setAttribute("aria-expanded", "true"); } }
  function closeMenu() { if (menu) { menu.hidden = true; langBtn.setAttribute("aria-expanded", "false"); } }
  if (langBtn) langBtn.addEventListener("click", function (e) {
    e.stopPropagation();
    if (menu && menu.hidden) openMenu(); else closeMenu();
  });
  document.addEventListener("click", function (e) { if (menu && !menu.contains(e.target)) closeMenu(); });
  document.addEventListener("keydown", function (e) { if (e.key === "Escape") closeMenu(); });

  var initial = null;
  try { initial = localStorage.getItem("vance-lang"); } catch (e) {}
  if (CODES.indexOf(initial) < 0) {
    initial = "en";
    var prefs = navigator.languages || [navigator.language || "en"];
    for (var i = 0; i < prefs.length; i++) {
      var c = String(prefs[i]).slice(0, 2).toLowerCase();
      if (CODES.indexOf(c) >= 0) { initial = c; break; }
    }
  }
  if (initial === "en") paint("en", null);
  else {
    /* hide the English flash briefly; never longer than the fallback */
    root.classList.add("i18n-loading");
    var reveal = function () { root.classList.remove("i18n-loading"); };
    setTimeout(reveal, 1200);
    applyLang(initial).then(reveal, reveal);
  }
})();
